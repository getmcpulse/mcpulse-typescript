import { createHash } from "node:crypto";
import { describe, expect, it } from "vitest";
import { fingerprint, normalise_description } from "../src/describe.js";
import { stem } from "../src/stem.js";
import stem_fixture from "./fixtures/stem.json";
import norm_fixture from "./fixtures/description_norm.json";

/**
 * The description fingerprints, and the two conformance suites behind them.
 *
 * There are ten MCPulse SDKs, and a description hashed in a Python server has
 * to equal the same description hashed in a Go one — otherwise one tool looks
 * like two the moment a customer runs a polyglot fleet, and the churn timeline
 * fills with changes that never happened.
 *
 * So both halves are pinned by fixtures rather than by prose:
 *
 *   `fixtures/stem.json`             13,160 words, generated by the schema
 *                                    study's `scripts/04_stem_fixture.py`. The
 *                                    same file the web checker is held to.
 *   `fixtures/description_norm.json` the normalised string and its hash, for the
 *                                    cases where two languages could disagree.
 *
 * Never regenerate either to make a failing test pass. These hashes are in the
 * product's history, and rewriting them rewrites what every stored row means.
 */

describe("the stemmer matches every other MCPulse SDK", () => {
  it("reproduces all 13,160 fixture words", () => {
    const cases = Object.entries(stem_fixture.cases as Record<string, string>);
    const wrong = cases.filter(([word, expected]) => stem(word) !== expected);

    expect(cases.length).toBeGreaterThan(13_000);
    expect(wrong.slice(0, 10)).toEqual([]);
  });

  it("merges the pair the whole correction came from", () => {
    // analyze_job_description: "…what a job posting actually screens on."
    // optimize_resume:         "…so it passes ATS screening."
    expect(stem("screens")).toBe(stem("screening"));
    expect(stem("screening")).toBe("screen");
  });

  it("leaves three-letter acronyms alone", () => {
    // Porter reads the trailing `s` as a plural and returns `at`, which is also
    // a stopword — so the default would delete the most diagnostic noun on a
    // resume server rather than sharpen it.
    expect(stem("ats")).toBe("ats");
    expect(stem("ids")).toBe("ids");
  });
});

describe("normalising a description", () => {
  it("reproduces every conformance case", () => {
    for (const fixture of norm_fixture.fixtures) {
      expect(normalise_description(fixture.description), fixture.name).toBe(fixture.normalised);

      const hashed = createHash("sha256")
        .update(fixture.normalised, "utf8")
        .digest("hex")
        .slice(0, 12);
      expect(hashed, fixture.name).toBe(fixture.description_norm);
    }
  });

  it("collapses the two descriptions that are one description", () => {
    // The reason a second hash exists at all. Exact hashing calls these two
    // different, and they are not.
    const a = normalise_description("Search for threads in the user's mailbox");
    const b = normalise_description("Search threads in a user's mailbox");
    expect(a).toBe(b);
  });

  it("does not collapse tools that merely share a verb", () => {
    // `list` and `get` are content on an MCP server, not filler. Dropping them
    // would converge the two tools most worth telling apart.
    expect(normalise_description("List the orders")).not.toBe(
      normalise_description("Get the order"),
    );
  });

  it("folds only ASCII case, so a Turkish locale cannot change a hash", () => {
    expect(normalise_description("SEARCH")).toBe(normalise_description("search"));
    // `İ` is left exactly as it arrived rather than lowercased by a rule that
    // differs between the ten languages this has to agree across.
    expect(normalise_description("İ")).toBe(normalise_description("İ"));
  });
});

describe("fingerprinting a tool", () => {
  const tool = {
    description: "Search the threads in a user's mailbox.",
    inputSchema: { type: "object", properties: { q: { type: "string" } } },
  };

  it("gives three hashes of twelve hex characters", () => {
    const print = fingerprint(tool);
    for (const value of Object.values(print)) expect(value).toMatch(/^[0-9a-f]{12}$/);
  });

  it("is stable across key order in the schema", () => {
    // Canonicalised, so a formatter or a refactor that reorders the declaration
    // does not read as an interface change.
    const reordered = {
      description: tool.description,
      inputSchema: { properties: { q: { type: "string" } }, type: "object" },
    };
    expect(fingerprint(reordered).schema_hash).toBe(fingerprint(tool).schema_hash);
  });

  it("separates a wording change from an interface change", () => {
    const reworded = { ...tool, description: "Search threads in the user's mailbox." };
    const print = fingerprint(tool);
    const after = fingerprint(reworded);

    expect(after.schema_hash).toBe(print.schema_hash);
    expect(after.description_hash).not.toBe(print.description_hash);
    // And the normalised hash says the description did not really change, which
    // is what stops a reworded sentence showing up as churn worth investigating.
    expect(after.description_norm).toBe(print.description_norm);
  });

  it("survives a schema that will not serialise", () => {
    const circular: Record<string, unknown> = { type: "object" };
    circular.self = circular;
    expect(() => fingerprint({ description: "x", inputSchema: circular })).not.toThrow();
    expect(fingerprint({ description: "x", inputSchema: circular }).schema_hash).toBe(
      "000000000000",
    );
  });

  it("a missing description is a description", () => {
    // The empty string, hashed. Not a special case — two tools that both forgot
    // one have genuinely converged on the same wording.
    expect(fingerprint({}).description_hash).toBe(fingerprint({ description: "" }).description_hash);
  });
});
